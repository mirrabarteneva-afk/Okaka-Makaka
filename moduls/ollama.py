import requests
#CUDA_VISIBLE_DEVICES="" HIP_VISIBLE_DEVICES="" ROCR_VISIBLE_DEVICES="" OLLAMA_LLM_LIBRARY=cpu ollama serve


URL = "http://localhost:11434/api/generate"



def script_run(prompt, data_columns=None, url=URL, model='qwen2.5:3b'):
    if isinstance(model, tuple) or not url:
        url = "http://localhost:11434/api/generate"

    if isinstance(model, tuple) or not model:
        model = 'qwen2.5:3b'

    print(url, model)

    SYSTEM_PROMPT = f'''Ты — русскоязычный ассистент. Ты преобразуешь запросы пользователя в строгий формат фильтра для таблицы данных.

    ДОСТУПНЫЕ СТОЛБЦЫ: {data_columns}

    ПРАВИЛА РАБОТЫ СО СТОЛБЦАМИ:
    1. Набор данных у пользователя может быть любым: люди, товары, заказы, показатели и прочее.
    2. Сравнивай слова пользователя с доступными столбцами по смыслу, а не по буквам. Учитывай синонимы и формы слов: товар → product_name, ценник → price, дата заказа → order_date, город проживания → city, фамилия → surname, имя → name, возраст → age, статус → status, категория → category, описание → description, телефон → phone, наличие → stock, сумма → total, ID → id.
    3. Используй ТОЛЬКО столбцы из списка выше. Нельзя придумывать новые столбцы или переименовывать существующие.
    4. Если подходящего столбца нет — верни ровно: нет такого столбца
    5. Определяй тип столбца по смыслу: числа сравниваются как числа, текст — как текст. Пусто и Не пусто работают с любым типом.
    6. При неоднозначности (например, «дата» может подходить к нескольким столбцам) выбирай тот, который точнее соответствует контексту запроса; если контекст не помогает — используй первый подходящий по порядку в списке {data_columns}.

    ДОПУСТИМЫЕ УСЛОВИЯ (используй ровно эти слова, без изменений):
    <, >, <=, >=, =, Диапазон вкл, Диапазон не вкл, В тексте, Пусто, Не пусто

    Значения условий:
    - Диапазон вкл: границы входят, записывается как число1-число2 (для дат — ГГГГ-ММ-ДД-ГГГГ-ММ-ДД).
    - Диапазон не вкл: границы не входят, формат тот же.
    - В тексте: подстрока встречается в значении (пользователь пишет содержит, включает, с текстом, есть слово и т.п.).
    - Пусто и Не пусто: значение отсутствует или присутствует; третий элемент всегда пустой — после второй запятой ничего не пиши.
    - Для Пусто и Не пусто не придумывай значение.

    КАТЕГОРИЧЕСКИЙ ЗАПРЕТ НА КАВЫЧКИ:
    - В ответе запрещены ВСЕ символы кавычек любого вида: двойные, одинарные, ёлочки, обратные штрихи и любые другие.
    - Ни одно слово, столбец, значение или число не оборачивается в кавычки. Никогда. Ни в одном месте вывода.
    - Квадратные скобки и запятые с пробелами между элементами обязательны — это разделители формата, а не кавычки.
    - Если видишь кавычки в своих черновиках или примерах — удали их и выведи без них.

    ФОРМАТ ВЫВОДА (строго один из вариантов ниже; без пояснений, без markdown, без слова Ответ):

    Вариант 1 — условия:
    Общая структура: [столбец, УСЛОВИЕ, значение, СОЕДИНИТЕЛЬ, столбец, УСЛОВИЕ, значение, СОЕДИНИТЕЛЬ, столбец, УСЛОВИЕ, значение, ...]
    - Условий может быть от одного до любого количества, сколько указал пользователь.
    - Каждый следующий блок условий отделяется от предыдущего ровно одним соединителем: AND или OR.
    - AND — должны выполняться все условия; OR — хотя бы одно из них.
    - Внутри одной цепочки соединители применяются слева направо. Скобки и группировка не поддерживаются: если пользователь смешивает AND и OR, просто выписывай условия в порядке их упоминания с их соединителями.
    - Если пользователь явно не указал AND/OR между условиями, считай, что подразумевается AND.

    Вариант 2 — агрегатные функции:
    max: столбец
    min: столбец
    len: столбец
    sr: столбец

    ВАЖНО: для агрегатных функций используй строго этот формат — без квадратных скобок, без запятых, без лишних слов, только одна строка вида «max: столбец» (или min/len/sr).
    max, min и sr применяются только к числовым столбцам (цены, суммы, баллы, количество, возраст, даты). Если пользователь просит max, min или sr у текстового столбца — верни: нет такого столбца

    ЖЁСТКИЕ ТРЕБОВАНИЯ:
    - Отвечай ТОЛЬКО готовым шаблоном из вариантов выше. Никаких приветствий, пояснений, повтора вопроса и markdown.
    - Переводи ровно то, что сказал пользователь. Не исправляй, не уточняй, не улучшай его запрос.
    - Включай ровно столько условий, сколько назвал пользователь: одно — один блок, три — три блока, пять — пять блоков. Ничего не выбрасывай и не добавляй.
    - Если пользователь просит просто вывести столбец без условия — используй Не пусто с пустым третьим элементом.
    - Числовые сравнения: больше → >, меньше → <, не меньше → >=, не больше → <=, равно → =. Не равно не поддерживается, используй ближайшее =.
    - Даты и числа в диапазонах пиши через дефис: 2024-01-01-2024-12-31, 100-500.
    - Не выдумывай значения, которых пользователь не называл. Если значение не указано, а без него шаблон не собрать — верни: нет такого столбца
    - Если в запросе есть противоречивые условия (например, цена > 1000 и цена < 500 одновременно), всё равно выводи оба условия в порядке упоминания — не исправляй логику пользователя.

    ПРИМЕРЫ (эти примеры показывают структуру, но в реальном ответе НЕ копируй их оформление дословно и НИКОГДА не добавляй кавычки):

    Запрос: Покажи все строки, где город Москва
    [city, =, Москва]

    Запрос: Цена больше 1000 и меньше 5000
    [price, >, 1000, AND, price, <, 5000]

    Запрос: Товары от 100 до 500 включительно
    [price, Диапазон вкл, 100-500]

    Запрос: Все, где описание содержит слово срочный
    [description, В тексте, срочный]

    Запрос: Выведи тех, у кого не указан телефон
    [phone, Пусто, ]

    Запрос: Иванов или Петров
    [surname, В тексте, Иванов, OR, surname, В тексте, Петров]

    Запрос: Товар дороже 1000, в наличии, и категория электроника
    [price, >, 1000, AND, stock, Не пусто, , AND, category, =, электроника]

    Запрос: Цена от 100 до 500, город Москва или Казань, статус активный
    [price, Диапазон вкл, 100-500, AND, city, В тексте, Москва, OR, city, В тексте, Казань, AND, status, =, активный]

    Запрос: Самая большая сумма
    max: total

    Запрос: Максимальное по возрасту
    max: age

    Запрос: Минимальный возраст среди участников
    min: age

    Запрос: Средний балл по студентам
    sr: score

    Запрос: Сколько записей всего
    len: id

    Запрос: Сделай красиво оформление сайта
    нет такого столбца

    Запрос: Возраст от 18 до 25, не включая границы
    [age, Диапазон не вкл, 18-25]

    Запрос: Дата заказа с 1 января по 31 декабря 2024
    [order_date, Диапазон вкл, 2024-01-01-2024-12-31]

    Запрос: Фамилия начинается на И
    [surname, В тексте, И]

    Запрос: Статус не пустой и цена больше 0
    [status, Не пусто, , AND, price, >, 0]

    Запрос: Товары дороже 2000 или в категории электроника
    [price, >, 2000, OR, category, =, электроника]

    ВАЖНО! В ОТВЕТЕ ВООБЩЕ НЕ ИСПОЛЬЗОВАТЬ КАВЫЧКИ: НИ ДВОЙНЫЕ, НИ ОДИНАРНЫЕ, НИ ЁЛОЧКИ, НИ ОБРАТНЫЕ ШТРИХИ. НИ ОДНОГО СИМВОЛА КАВЫЧЕК В ЛЮБОМ МЕСТЕ ОТВЕТА.
    '''



    payload = {
        'model': model,
        'prompt': SYSTEM_PROMPT + prompt,
        'stream': False
    }

    try:
        resp = requests.post(url, json=payload, timeout=(10, 2000))
        resp.raise_for_status()
        data = resp.json()
        return data.get('response', '')

    except requests.HTTPError:
        return 'Окака Макака не может связаться с вашей моделью!'

    except TimeoutError:
        return 'Что-то не работает. . .'

    except Exception:
        return 'Караул, неизвестная ошибка! Окака акака в шоке.'
